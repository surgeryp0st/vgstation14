#!/usr/bin/env python3
"""
Generates vg13's plasmaman containment suits and helmets: the RSIs under Resources/Textures/_VG/obj/clothing/plasmaman/
and Resources/Prototypes/_VG/Entities/Clothing/plasmaman.yml. Only variants with sprites in both the item and worn
sheets are made (name and sprite come from code/modules/clothing/spacesuits/plasmamen.dm).

    plasmaman_gear.py ../vgstation13
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dmi2rsi

vg13 = sys.argv[1] if len(sys.argv) > 1 else "../vgstation13"
repo = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
tex_root = os.path.join(repo, "Resources/Textures/_VG/obj/clothing/plasmaman")
yml_path = os.path.join(repo, "Resources/Prototypes/_VG/Entities/Clothing/plasmaman.yml")

text = open(os.path.join(vg13, "code/modules/clothing/spacesuits/plasmamen.dm")).read()
classes = {}
for m in re.finditer(r"^/obj/item/clothing/(suit|head/helmet)/space/plasmaman([\w/]*)\n((?:\t.*\n|\n)*)", text, re.M):
    kind = "suit" if m.group(1) == "suit" else "helmet"
    path = m.group(2)
    body = m.group(3)
    name = re.search(r'^\tname = "([^"]*)"', body, re.M)
    icon = re.search(r'^\ticon_state = "([^"]*)"', body, re.M)
    classes[(kind, path)] = (name.group(1) if name else None, icon.group(1) if icon else None)


def sheet(path):
    return dmi2rsi.parse_description(__import__("PIL.Image", fromlist=["Image"]).open(os.path.join(vg13, path)).info["Description"])[2]


def states(path):
    return {s.name for s in sheet(path)}


obj = {"suit": states("icons/obj/clothing/suits.dmi"), "helmet": states("icons/obj/clothing/hats.dmi")}
worn = {"suit": states("icons/mob/species/plasmaman/suit.dmi"), "helmet": states("icons/mob/species/plasmaman/head.dmi")}
srcs = {
    "suit": ("icons/obj/clothing/suits.dmi", "icons/mob/species/plasmaman/suit.dmi"),
    "helmet": ("icons/obj/clothing/hats.dmi", "icons/mob/species/plasmaman/head.dmi"),
}

items = []
for (kind, path), (name, icon) in classes.items():
    if not name or not icon:
        continue
    if icon not in obj[kind] or icon not in worn[kind]:
        continue
    if kind == "helmet":
        if not icon.endswith("0") or icon[:-1] + "1" not in obj[kind] or icon[:-1] + "1" not in worn[kind]:
            continue
    key = "".join(p.capitalize() if p.islower() else p for p in path.split("/")[-1:]) if path else ""
    items.append((kind, key, name, icon))

shutil.rmtree(tex_root, ignore_errors=True)
tmp = tempfile.mkdtemp()
converted = {}
for kind in ("suit", "helmet"):
    for i, src in enumerate(srcs[kind]):
        out = os.path.join(tmp, f"{kind}{i}.rsi")
        dmi2rsi.convert(os.path.join(vg13, src), out, quiet=True)
        converted[(kind, i)] = out


def meta_of(rsi):
    return json.load(open(os.path.join(rsi, "meta.json")))


def add(outdir, rsi, state, newname, meta, states_out):
    shutil.copy(os.path.join(rsi, state + ".png"), os.path.join(outdir, newname + ".png"))
    e = next(s for s in meta["states"] if s["name"] == state)
    states_out.append(dict(e, name=newname))


# vg13 armor for the gear (plasmamen.dm; the helmet's comes from /obj/item/clothing/head/helmet/space). One vgClothing
# per item, since vgClothing can't name the abstract bases.
ARMOR = {
    "Suit": ("/obj/item/clothing/suit/space/plasmaman", "{ bio: 100 }", "[ Arms, Feet, FullTorso, Hands, Legs ]", "1.4"),
    "Helmet": ("/obj/item/clothing/head/helmet/space/plasmaman", "{ bio: 100, rad: 50 }", "[ FullHead ]", None),
}


def write_armor(idents):
    out = ["# Generated by Tools/_VG/plasmaman_gear.py: vg13 armor for the plasmaman gear. Do not edit.\n"]
    for ident in idents:
        path, armor, coverage, slowdown = ARMOR["Suit" if ident.startswith("VgPlasmamanSuit") else "Helmet"]
        out.append(f"\n- type: vgClothing\n  id: {ident}\n  # {path}\n  armor: {armor}\n  coverage: {coverage}\n"
                   + (f"  slowdown: {slowdown}\n" if slowdown else ""))
    open(os.path.join(repo, "Resources", "Prototypes", "_VG", "Clothing", "plasmaman.yml"), "w").write("".join(out))


yml = ["# Generated by Tools/_VG/plasmaman_gear.py from vg13's plasmamen.dm. Do not edit.\n"]
for kind, key, name, icon in items:
    ident = f"VgPlasmaman{'Suit' if kind == 'suit' else 'Helmet'}{key}"
    outdir = os.path.join(tex_root, ident.lower() + ".rsi")
    os.makedirs(outdir)
    objrsi, wornrsi = converted[(kind, 0)], converted[(kind, 1)]
    objmeta, wornmeta = meta_of(objrsi), meta_of(wornrsi)
    st = []
    if kind == "suit":
        add(outdir, objrsi, icon, "icon", objmeta, st)
        add(outdir, wornrsi, icon, "equipped-OUTERCLOTHING", wornmeta, st)
    else:
        lit = icon[:-1] + "1"
        add(outdir, objrsi, icon, "icon", objmeta, st)
        add(outdir, objrsi, lit, "icon-flash", objmeta, st)
        add(outdir, wornrsi, icon, "off-equipped-HELMET", wornmeta, st)
        add(outdir, wornrsi, lit, "on-equipped-HELMET", wornmeta, st)
    meta = dict(objmeta, states=st, copyright=objmeta["copyright"] + " and icons/mob/species/plasmaman")
    meta["size"] = objmeta["size"]
    json.dump(meta, open(os.path.join(outdir, "meta.json"), "w"), indent=2)
    open(os.path.join(outdir, "meta.json"), "a").write("\n")

    rsi = f"_VG/obj/clothing/plasmaman/{ident.lower()}.rsi"
    parent = "VgPlasmamanSuitBase" if kind == "suit" else "VgPlasmamanHelmetBase"
    yml.append(f"""
- type: entity
  parent: {parent}
  id: {ident}
  name: {name}
  components:
  - type: Sprite
    sprite: {rsi}
""" + ("" if kind == "suit" else """    layers:
    - state: icon
    - state: icon-flash
      visible: false
      map: [ "light" ]
""") + f"""  - type: Clothing
    sprite: {rsi}
""")

os.makedirs(os.path.dirname(yml_path), exist_ok=True)
open(yml_path, "w").write("".join(yml))
write_armor([f"VgPlasmaman{'Suit' if kind == 'suit' else 'Helmet'}{key}" for kind, key, _, _ in items])
print(f"{len(items)} items")
