#!/usr/bin/env python3
"""Generates the VgTest map and its test pills: a corridor with a room for each ported vg13 system.

    python3 Tools/_VG/make_test_map.py

Writes Resources/Maps/_VG/vg_test.yml and Resources/Prototypes/_VG/Entities/Test/pills.yml.
"""
import collections
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "Tools", "_VG", "dmm2map"))
import dmm2map  # noqa: E402

PI = 3.141592653589793
NORTH, SOUTH, EAST, WEST = PI, 0.0, PI / 2, 3 * PI / 2


def reagent_ids():
    ids = []
    for f in ("medicine", "narcotics", "toxins"):
        text = open(os.path.join(ROOT, "Resources", "Prototypes", "_VG", "Reagents", f + ".yml"), encoding="utf-8").read()
        ids += re.findall(r"^- type: vgReagent\n  id: (\S+)", text, re.M)
    return ids


def write_pills(ids):
    out = ["# Generated by Tools/_VG/make_test_map.py: one pill with a full dose of each vg13 reagent, for the VgTest map.", ""]
    for r in ids:
        name = "".join(p.capitalize() for p in re.split(r"[_\-]", r))
        out += [f"- type: entity", f"  parent: Pill", f"  id: VgTestPill{name}", f"  name: test pill ({r})",
                f"  components:", f"  - type: SolutionContainerManager", f"    solutions:", f"      food:", f"        maxVol: 20",
                f"        reagents:", f"        - ReagentId: {r}", f"          Quantity: 20", ""]
    path = os.path.join(ROOT, "Resources", "Prototypes", "_VG", "Entities", "Test", "pills.yml")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write("\n".join(out))
    return ["VgTestPill" + "".join(p.capitalize() for p in re.split(r"[_\-]", r)) for r in ids]


class Builder:
    def __init__(self):
        self.tilemap = {"Space": 0, "Plating": 1, "FloorSteel": 2, "FloorWhite": 3, "FloorReinforced": 4}
        self.tiles = {}
        self.placed = collections.defaultdict(list)

    def tile(self, x, y, name):
        self.tiles[(x, y)] = self.tilemap.setdefault(name, len(self.tilemap))

    def put(self, proto, x, y, rot=0.0):
        self.placed[proto].append((x, y, rot))

    def room(self, x0, y0, x1, y1, floor="FloorSteel", wall="WallSolid"):
        """Walled rectangle, walls on its border."""
        for x in range(x0, x1 + 1):
            for y in range(y0, y1 + 1):
                edge = x in (x0, x1) or y in (y0, y1)
                self.tile(x, y, "Plating" if edge else floor)
                if edge and not self.has(wall, x, y):
                    self.put(wall, x, y)

    def has(self, proto, x, y):
        return any(px == x and py == y for px, py, _ in self.placed[proto])

    def remove_wall(self, x, y):
        for proto in ("WallSolid", "WallReinforced"):
            self.placed[proto] = [p for p in self.placed[proto] if (p[0], p[1]) != (x, y)]

    def door(self, x, y, proto="Airlock"):
        self.remove_wall(x, y)
        self.put(proto, x, y)

    def shelf(self, protos, x, y, step=(1, 0), table="Table"):
        """A row of tables with one item on each."""
        for i, proto in enumerate(protos):
            tx, ty = x + step[0] * i, y + step[1] * i
            self.put(table, tx, ty)
            self.put(proto, tx, ty)

    def cable(self, proto, cells):
        for x, y in cells:
            self.put(proto, x, y)


def main():
    pills = write_pills(reagent_ids())
    b = Builder()
    W, N_ROOMS = 14, 4

    # Main corridor: walls at y=0 and y=4, floor y=1..3.
    length = W * N_ROOMS
    b.room(-8, 0, length, 4, floor="FloorWhite")
    for x in range(1, length):
        b.remove_wall(x, 0)
        b.remove_wall(x, 4)
        b.tile(x, 0, "FloorWhite")
        b.tile(x, 4, "FloorWhite")
    # Rebuild the corridor walls only where no room attaches (rooms draw their own).
    for x in range(-8, length + 1):
        b.put("WallSolid", x, 0) if not any(r_x0 <= x <= r_x0 + W for r_x0 in range(0, length, W)) else None

    rooms = {}
    for i in range(N_ROOMS):
        x0 = i * W
        rooms[("N", i)] = (x0, 4, x0 + W, 12)
        rooms[("S", i)] = (x0, -8, x0 + W, 0)
    DOOR = 3  # each room's door is this many tiles in from its west wall; keep that column clear inside
    for (side, i), (x0, y0, x1, y1) in rooms.items():
        b.room(x0, y0, x1, y1)
        door_y = 4 if side == "N" else 0
        b.door(x0 + DOOR, door_y, "AirlockGlass")

    def inner(side, i):
        x0, y0, x1, y1 = rooms[(side, i)]
        return x0 + 1, y0 + 1, x1 - 1, y1 - 1

    # --- power: generator -> substation -> MV along the corridor -> one APC per room, extension cable inside.
    b.put("DebugGenerator", -7, 2)
    b.cable("CableHV", [(x, 2) for x in range(-7, -3)])
    b.put("SubstationBasic", -3, 2)
    b.cable("CableMV", [(x, 1) for x in range(-3, length)] + [(-3, 2)])
    for (side, i), (x0, y0, x1, y1) in rooms.items():
        ax = x0 + 6
        ay = y0 + 1 if side == "N" else y1 - 1
        corridor_y = 1
        ys = range(corridor_y, ay + 1) if side == "N" else range(ay, corridor_y + 1)
        b.cable("CableMV", [(ax, y) for y in ys])
        b.put("APCBasic", ax, ay, SOUTH if side == "N" else NORTH)
        ix0, iy0, ix1, iy1 = inner(side, i)
        b.cable("CableApcExtension", [(x, y) for x in range(ix0, ix1 + 1) for y in range(iy0, iy1 + 1)])
        for lx in (ix0 + 2, ix1 - 2):
            b.put("PoweredlightLED", lx, iy1 if side == "N" else iy0, SOUTH if side == "N" else NORTH)
    # The corridor is its own area: an APC on its north wall, west of the rooms, and LV along its whole length.
    b.cable("CableMV", [(-2, 2), (-2, 3)])
    b.put("APCBasic", -2, 3, NORTH)
    b.cable("CableApcExtension", [(x, y) for x in range(-7, length) for y in range(1, 4)])
    for x in range(4, length, 8):
        b.put("PoweredlightLED", x, 3, SOUTH)

    # --- the emergency shuttle docks at the west end of the corridor.
    b.door(-8, 1, "AirlockExternalGlassShuttleEmergencyLocked")
    b.placed["AirlockExternalGlassShuttleEmergencyLocked"][-1] = (-8, 1, WEST)

    # --- start: latejoin and observer spawns in the west of the corridor, a locker with gear.
    b.put("SpawnPointLatejoin", -5, 1)
    b.put("SpawnPointPassenger", -4, 1)
    b.put("SpawnPointObserver", -5, 3)

    # --- room N0: species. One of each mob.
    x0, y0, x1, y1 = inner("N", 0)
    species = ["MobHuman", "MobVox", "MobDiona", "MobReptilian", "MobSkeletonPerson", "MobSlimePerson", "MobGrey", "MobInsectoid",
               "MobMushroom", "MobPlasmaman", "MobSkrell", "MobTajaran"]
    for i, mob in enumerate(species):
        b.put(mob, x0 + 1 + (i % 6) * 2, y0 + 2 + (i // 6) * 3)

    # --- room N1: combat. Weapons, armor, dummies.
    x0, y0, x1, y1 = inner("N", 1)
    b.shelf(["Stunbaton", "WeaponTaser", "WeaponDisabler", "Handcuffs", "Crowbar", "WeaponPistolMk58", "WeaponShotgunKammerer",
             "WeaponLaserCarbine"], x0 + 1, y1, (1, 0))
    b.shelf(["ClothingOuterArmorBasic", "ClothingOuterArmorRiot", "ClothingOuterArmorBulletproof", "ClothingHeadHelmetBasic",
             "ClothingHeadHelmetRiot", "ClothingHeadHelmetSwat"], x0 + 1, y1 - 2, (1, 0), table="Rack")
    for i in range(3):
        b.put("MobHuman", x0 + 2 + i * 4, y0 + 1)
    b.put("TargetHuman", x1 - 1, y0 + 1)

    # --- room N2: medical.
    x0, y0, x1, y1 = inner("N", 2)
    b.shelf(["VgBruisePack", "VgOintment", "VgSplint", "VgAdvancedTraumaKit", "VgAdvancedBurnKit", "VgBandaid", "MedkitFilled",
             "MedkitAdvancedFilled", "HandheldHealthAnalyzer", "Hypospray"], x0 + 1, y1, (1, 0))
    for i in range(3):
        b.put("OperatingTable", x0 + 2 + i * 4, y0 + 2)
        b.put("MobHuman", x0 + 2 + i * 4, y0 + 2)
    b.put("MedicalScanner", x1 - 1, y0 + 1)
    b.put("VendingMachineMedical", x0 + 1, y0 + 1)

    # --- room N3: chemistry.
    x0, y0, x1, y1 = inner("N", 3)
    b.put("ChemDispenser", x0 + 1, y1)
    b.put("ChemDispenser", x0 + 3, y1)
    b.put("ChemMaster", x0 + 5, y1)
    b.shelf(["Beaker", "Beaker", "LargeBeaker", "LargeBeaker", "Syringe", "Syringe", "Dropper", "KitchenReagentGrinder", "JugWater",
             "JugSulfuricAcid"], x0 + 1, y1 - 2, (1, 0))
    b.shelf(["Bucket", "SprayBottleWater"], x0 + 1, y0 + 1, (1, 0))

    # --- rooms S0 and S1: every test pill, one row of tables per 10.
    for i, key in enumerate([("S", 0), ("S", 1)]):
        x0, y0, x1, y1 = inner(*key)
        chunk = pills[i * 30:(i + 1) * 30] if len(pills) > 30 else (pills if i == 0 else [])
        columns = [x for x in range(x0, x1 + 1) if x != x0 - 1 + DOOR]
        for j, pill in enumerate(chunk):
            row, col = divmod(j, len(columns))
            b.put("Table", columns[col], y1 - row * 2)
            b.put(pill, columns[col], y1 - row * 2)
    if len(pills) > 60:
        print("warning: more pills than fit", len(pills))

    # --- room S2: atmos and fire.
    x0, y0, x1, y1 = inner("S", 2)
    for i, can in enumerate(["OxygenCanister", "NitrogenCanister", "PlasmaCanister", "NitrousOxideCanister", "CarbonDioxideCanister"]):
        b.put(can, x0 + 1 + i * 2, y1)
    b.put("WeldingFuelTankFull", x0 + 1, y0 + 2)
    b.put("WaterTankFull", x0 + 3, y0 + 2)
    b.shelf(["Igniter", "GasAnalyzer", "GeigerCounter", "Welder", "FireExtinguisher", "ClothingMaskGas", "ClothingMaskBreath",
             "EmergencyOxygenTankFilled", "Flare"], x0 + 1, y0, (1, 0))

    # --- room S3: food and drink, to watch hunger.
    x0, y0, x1, y1 = inner("S", 3)
    b.shelf(["FoodBurgerBacon", "FoodPizzaPineapple", "FoodApple", "DrinkBeerglass", "DrinkColaCan"], x0 + DOOR, y1, (1, 0))
    b.put("VendingMachineCigs", x0 + 1, y0 + 1)
    b.put("VendingMachineVendomat", x0 + 3, y0 + 1)

    dest = os.path.join(ROOT, "Resources", "Maps", "_VG", "vg_test.yml")
    # No gravity generator: the test grid has gravity of its own, so it doesn't depend on power.
    n = dmm2map.write_map(dest, b.tilemap, b.tiles, b.placed, station="VgTest", inherent_gravity=True)
    print(f"{dest}: {len(b.tiles)} tiles, {n} entities; {len(pills)} test pills")


if __name__ == "__main__":
    main()
